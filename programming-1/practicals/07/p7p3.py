# Write a program that uses a while loop to go through the first 50 
# integers and prints out each number and the square of the number.

# Pseudocode
# initiate a counter and set its value to 1
# counter = 1
# while counter <= 50:
#     print counter and counter squared
#     increment counter by 1

# program terminates

counter = 1
while counter <= 50:
    print("Number is:",counter,"and its square is:", counter**2)
    counter += 1

print("Program terminated")
